#!/bin/sh
# Establish global mise configuration before the first bootstrap.
set -eu

validate_configuration() {
  for name in config.toml; do
    [ -f "$REPO_DIR/dots/.config/mise/$name" ] || {
      printf 'Missing mise configuration: %s\n' "$name" >&2
      exit 1
    }
  done


}

link_configuration() {
  mkdir -p "$CONFIG_DIR"

  # Preserve existing configs when adopting or switching checkouts.
  backup_dir=
  for name in config.toml; do
    source=$REPO_DIR/dots/.config/mise/$name
    target=$CONFIG_DIR/$name
    if [ -L "$target" ] && [ "$(readlink "$target")" = "$source" ]; then
      continue
    fi
    if [ -e "$target" ] || [ -L "$target" ]; then
      if [ -z "$backup_dir" ]; then
        backup_dir=$(mktemp -d "$CONFIG_DIR/.dotfiles-backup.XXXXXX")
        printf 'Existing mise configs saved in %s\n' "$backup_dir"
      fi
      mv -- "$target" "$backup_dir/$name"
    fi
    ln -s -- "$source" "$target"
  done
}

retire_legacy_context() {
  # Preserve old generated context and checkout links when migrating.
  for name in config.workstation.toml config.server.toml dotfiles conf.d/00-dotfiles-context.toml; do
    target=$CONFIG_DIR/$name
    case "$name" in
      conf.d/*)
        [ -f "$target" ] && [ ! -L "$target" ] || continue
        IFS= read -r header < "$target" || continue
        [ "$header" = '# Generated by configure_mise.sh; rerun after moving the checkout.' ] || continue ;;
      *)
        [ -L "$target" ] || continue
        expected=$REPO_DIR/dots/.config/mise/$name
        [ "$name" != dotfiles ] || expected=$REPO_DIR
        [ "$(readlink "$target")" = "$expected" ] || continue ;;
    esac
    if [ -z "$backup_dir" ]; then
      backup_dir=$(mktemp -d "$CONFIG_DIR/.dotfiles-backup.XXXXXX")
      printf 'Previous mise configuration saved in %s\n' "$backup_dir"
    fi
    mv -- "$target" "$backup_dir/$(basename "$name")"
  done
}

main() {
  SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
  REPO_DIR=$(CDPATH= cd -- "${1:-$SCRIPT_DIR/../..}" && pwd)
  CONFIG_DIR=${MISE_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/mise}

  validate_configuration
  link_configuration
  retire_legacy_context
}

main "$@"
