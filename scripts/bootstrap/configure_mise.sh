#!/bin/sh
# Establish global mise configuration before the first bootstrap.
set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPO_DIR=$(CDPATH= cd -- "${1:-$SCRIPT_DIR/../..}" && pwd)
CONFIG_DIR=${MISE_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/mise}

for name in config.toml config.workstation.toml config.server.toml; do
  [ -f "$REPO_DIR/dots/.config/mise/$name" ] || {
    printf 'Missing mise configuration: %s\n' "$name" >&2
    exit 1
  }
done

# Escape a TOML basic string without requiring Python on a fresh machine.
case "$REPO_DIR" in
  *'
'*|*"$(printf '\r')"*|*"$(printf '\t')"*)
    printf 'Repository paths containing control characters are unsupported.\n' >&2
    exit 1 ;;
esac
escaped_repo=$(printf '%s' "$REPO_DIR" | sed 's/\\/\\\\/g; s/"/\\"/g')
mkdir -p "$CONFIG_DIR/conf.d"

# Preserve existing configs when adopting or switching checkouts.
backup_dir=
for name in config.toml config.workstation.toml config.server.toml dotfiles; do
  source=$REPO_DIR/dots/.config/mise/$name
  if [ "$name" = dotfiles ]; then source=$REPO_DIR; fi
  target=$CONFIG_DIR/$name
  if [ -L "$target" ] && [ "$(readlink "$target")" = "$source" ]; then
    continue
  fi
  if [ -e "$target" ] || [ -L "$target" ]; then
    if [ -z "$backup_dir" ]; then
      backup_dir=$(mktemp -d "$CONFIG_DIR/.dotfiles-backup.XXXXXX")
      printf 'Existing mise configs saved in %s\n' "$backup_dir"
    fi
    mv -- "$target" "$backup_dir/$name"
  fi
  ln -s -- "$source" "$target"
done

# Machine-local checkout context also works when mise runs outside the repo.
context=$(mktemp "$CONFIG_DIR/conf.d/.dotfiles-context.XXXXXX")
trap 'rm -f -- "$context"' EXIT HUP INT TERM
printf '# Generated by configure_mise.sh; rerun after moving the checkout.\n[vars]\ndotfiles_repo = "%s"\n\n[settings.dotfiles]\nroot = "%s/dots"\n' "$escaped_repo" "$escaped_repo" > "$context"
mv -- "$context" "$CONFIG_DIR/conf.d/00-dotfiles-context.toml"
printf 'Global mise configuration linked to %s\n' "$REPO_DIR"
