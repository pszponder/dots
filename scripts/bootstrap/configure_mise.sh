#!/bin/sh
# Establish global mise configuration before the first bootstrap.
set -eu

validate_configuration() {
  for name in config.toml; do
    [ -f "$REPO_DIR/dots/.config/mise/$name" ] || {
      printf 'Missing mise configuration: %s\n' "$name" >&2
      exit 1
    }
  done


}

link_configuration() {
  mkdir -p "$CONFIG_DIR"

  for name in config.toml; do
    source=$REPO_DIR/dots/.config/mise/$name
    target=$CONFIG_DIR/$name
    if [ -L "$target" ] && [ "$(readlink "$target")" = "$source" ]; then
      continue
    fi
    if ln -sT -- "$source" "$target"; then continue; fi
    printf 'Could not link global mise configuration: %s\n' "$target" >&2
    sh "$SCRIPT_DIR/confirm_replacements.sh" "${3:-}"
    ln -sTf -- "$source" "$target"
  done
}

retire_legacy_context() {
  # Preserve old generated context and checkout links when migrating.
  for name in config.workstation.toml config.server.toml dotfiles conf.d/00-dotfiles-context.toml; do
    target=$CONFIG_DIR/$name
    case "$name" in
      conf.d/*)
        [ -f "$target" ] && [ ! -L "$target" ] || continue
        IFS= read -r header < "$target" || continue
        [ "$header" = '# Generated by configure_mise.sh; rerun after moving the checkout.' ] || continue ;;
      *)
        [ -L "$target" ] || continue
        expected=$REPO_DIR/dots/.config/mise/$name
        [ "$name" != dotfiles ] || expected=$REPO_DIR
        [ "$(readlink "$target")" = "$expected" ] || continue ;;
    esac
    rm -f -- "$target"
  done
}


toml_string() {
  printf '%s' "$1" | awk '
    BEGIN { ORS="" }
    { if (NR > 1) printf "\\n";
      for (i=1; i<=length($0); i++) {
        c=substr($0,i,1)
        if (c == "\\") printf "\\\\";
        else if (c == "\"") printf "\\\"";
        else if (c == "\t") printf "\\t";
        else if (c == "\r") printf "\\r";
        else printf "%s", c;
      }
    }'
}

save_context() {
  context=$CONFIG_DIR/conf.d/01-dotfiles-machine.toml
  profile=${2:-}
  if [ -z "$profile" ] && [ -f "$context" ]; then
    profile=$(sed -n 's/^dotfiles_profile = "\([a-z-]*\)"$/\1/p' "$context")
  fi
  profile=${profile:-server}
  case "$profile" in
    server|workstation-ubuntu|workstation-debian|workstation-fedora|workstation-arch|workstation-ublue) ;;
    *) printf 'Invalid dotfiles profile: %s\n' "$profile" >&2; exit 1 ;;
  esac
  mkdir -p "$CONFIG_DIR/conf.d"
  temporary=$(mktemp "$CONFIG_DIR/conf.d/.context.XXXXXX")
  {
    printf '# Generated by configure_mise.sh; rerun after moving the checkout.\n'
    printf '[settings.dotfiles]\nroot = "%s/dots"\n' "$(toml_string "$REPO_DIR")"
    printf '[vars]\ndotfiles_repo = "%s"\ndotfiles_profile = "%s"\n' "$(toml_string "$REPO_DIR")" "$profile"
  } > "$temporary"
  mv -- "$temporary" "$context"
}

main() {
  SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
  REPO_DIR=$(CDPATH= cd -- "${1:-$SCRIPT_DIR/../..}" && pwd)
  CONFIG_DIR=${MISE_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/mise}

  validate_configuration
  case "${2:-server}" in server|workstation-ubuntu|workstation-debian|workstation-fedora|workstation-arch|workstation-ublue|'') ;; *) printf 'Invalid profile\n' >&2; exit 1 ;; esac
  link_configuration "$@"
  retire_legacy_context "$@"
  save_context "$@"
}

main "$@"
